const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
process.env.POS_DATA_DIR=fs.mkdtempSync(path.join(os.tmpdir(),'pos-test-'));
const app=require('../src/server');
const { db, hashPassword }=require('../src/security');
const { deviceDate, deviceDateTime }=require('../src/deviceTime');

test('offline acceptance flow',async t=>{
  const server=app.listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  t.after(()=>server.close());
  const base=`http://127.0.0.1:${server.address().port}/api`;
  let token;
  const call=async(method,url,body,expected=200)=>{
    const r=await fetch(base+url,{method,headers:{'content-type':'application/json',...(token?{authorization:'Bearer '+token}:{})},body:body===undefined?undefined:JSON.stringify(body)});
    const data=await r.json();assert.equal(r.status,expected,`${method} ${url}: ${JSON.stringify(data)}`);return data;
  };
  db.prepare("INSERT INTO users(username,password_hash,role,must_change_password,temporary_password_expires_at) VALUES(?,?,'SYSTEM_ADMIN',1,datetime('now','+1 day'))").run('systemadmin',hashPassword('Temp@123456'));
  let login=await call('POST','/auth/login',{username:'systemadmin',password:'Temp@123456'});token=login.token;
  assert.equal((await call('GET','/system/status',undefined,403)).mustChangePassword,true);
  login=await call('POST','/auth/change-password',{currentPassword:'Temp@123456',newPassword:'StrongSystem#123',confirmPassword:'StrongSystem#123'});token=login.token;
  const setup=await call('POST','/system/business',{name:'Downtown Coffee House',ownerName:'John Smith',adminUsername:'downtownadmin',defaultTaxRateBps:825},201);
  assert.ok(setup.admin.temporaryPassword);
  login=await call('POST','/auth/login',{username:'downtownadmin',password:setup.admin.temporaryPassword});token=login.token;
  login=await call('POST','/auth/change-password',{currentPassword:setup.admin.temporaryPassword,newPassword:'StrongOwner#123',confirmPassword:'StrongOwner#123'});token=login.token;
  const employee=await call('POST','/employees',{firstName:'Sarah',lastName:'Johnson',phone:'5125559088',jobRole:'Cashier',salaryCents:1800,salaryType:'HOURLY'},201);
  const cashier=await call('POST','/users',{username:'sarah',employeeId:employee.id},201);
  const category=await call('POST','/categories',{name:'Coffee'},201);
  const cappuccino=await call('POST','/products',{name:'Cappuccino',categoryId:category.id,priceCents:450},201);
  const latte=await call('POST','/products',{name:'Latte',categoryId:category.id,priceCents:500},201);
  login=await call('POST','/auth/login',{username:'sarah',password:cashier.temporaryPassword});token=login.token;
  login=await call('POST','/auth/change-password',{currentPassword:cashier.temporaryPassword,newPassword:'StrongCashier#123',confirmPassword:'StrongCashier#123'});token=login.token;
  await call('POST','/shifts/open',{openingCashCents:10000},201);
  let sale=await call('POST','/sales',{orderType:'TAKEAWAY',orderSource:'PHONE',customerName:'Michael Brown',customerPhone:'5125559988'},201);
  sale=await call('PUT',`/sales/${sale.id}/items/${cappuccino.id}`,{quantity:2});
  sale=await call('PUT',`/sales/${sale.id}/items/${latte.id}`,{quantity:1});
  assert.equal(sale.subtotal_cents,1400);
  assert.equal(sale.tax_cents,115);
  assert.equal(sale.total_cents,1515);
  const key='checkout-test-1';
  sale=await call('POST',`/sales/${sale.id}/checkout`,{idempotencyKey:key,paymentMethod:'CASH',cashReceivedCents:2000});
  assert.equal(sale.payment.change_cents,485);
  assert.equal(sale.status,'COMPLETED');
  assert.equal(sale.printJobs.length,0);
  const cashierInsights=await call('GET','/dashboard/insights');
  assert.equal(cashierInsights.weeklySales.length,7);
  assert.equal(cashierInsights.weeklySales.reduce((sum,day)=>sum+day.revenue_cents,0),1515);
  assert.equal(cashierInsights.topItems[0].name,'Cappuccino');
  assert.equal(cashierInsights.topItems[0].quantity,2);
  const again=await call('POST',`/sales/${sale.id}/checkout`,{idempotencyKey:key,paymentMethod:'CASH',cashReceivedCents:2000});
  assert.equal(again.id,sale.id);
  assert.equal((await call('PUT',`/sales/${sale.id}/items/${latte.id}`,{quantity:4},409)).error,'Sale is locked');
  await new Promise(resolve=>setTimeout(resolve,50));
  const detail=await call('GET',`/sales/${sale.id}`);
  assert.equal(detail.printJobs.length,0);
  const reprint=await call('POST',`/sales/${sale.id}/reprint`,{});
  assert.ok(reprint.id>0);
  assert.equal((await call('GET',`/sales/${sale.id}/print-jobs`)).length,1);
  const receiptPreview=(await call('GET',`/sales/${sale.id}/receipt-preview`)).text;
  assert.match(receiptPreview,/Cappuccino/);
  assert.ok(receiptPreview.includes(deviceDateTime(sale.completed_at)));
  let held=await call('POST','/sales',{orderType:'TAKEAWAY',orderSource:'POS'},201);
  held=await call('PUT',`/sales/${held.id}/items/${latte.id}`,{quantity:1});
  held=await call('PATCH',`/sales/${held.id}`,{discountType:'FIXED',discountValue:100});
  assert.equal(held.discount_cents,100);
  assert.ok((await call('GET','/sales/drafts')).some(row=>row.id===held.id));
  assert.equal((await call('GET',`/sales/${held.id}`)).items[0].quantity,1);
  await call('POST',`/sales/${held.id}/cancel`,{});
  assert.ok(!(await call('GET','/sales/drafts')).some(row=>row.id===held.id));
  const shift=(await call('GET','/shifts'))[0];
  const closed=await call('POST',`/shifts/${shift.id}/close`,{actualCashCents:11515});
  assert.equal(closed.difference_cents,0);
  login=await call('POST','/auth/login',{username:'downtownadmin',password:'StrongOwner#123'});token=login.token;
  const hours=Array.from({length:7},(_,day)=>({dayOfWeek:day,isClosed:day===0,openingTime:day===0?null:'09:00',closingTime:day===0?null:(day===6?'15:00':'18:00')}));
  const profile=await call('PATCH','/business',{name:'Downtown Coffee House',ownerName:'Jane Smith',phone:'5125551234',addressLine1:'10 Main Street',addressLine2:'Suite 200',city:'Austin',hours});
  assert.equal(profile.owner_name,'Jane Smith');
  assert.equal(profile.hours.length,7);
  assert.equal(profile.hours[0].is_closed,1);
  assert.equal(profile.hours[6].closing_time,'15:00');
  assert.equal((await call('GET','/business')).phone,'5125551234');
  const updatedReceipt=(await call('GET',`/sales/${sale.id}/receipt-preview`)).text;
  assert.match(updatedReceipt,/Downtown Coffee House/);
  assert.match(updatedReceipt,/10 Main Street/);
  assert.match(updatedReceipt,/Suite 200/);
  assert.match(updatedReceipt,/5125551234/);
  await call('PATCH','/business',{hours:[...hours.slice(0,6),hours[0]]},400);
  assert.equal((await call('GET','/business')).hours[6].closing_time,'15:00');
  const customer=await call('POST','/customers',{name:'Michael Brown',phone:'5125559988'});
  assert.equal((await call('GET','/customers?phone=5125559988'))[0].id,customer.id);
  await call('PATCH',`/customers/${customer.id}`,{name:'Michael B',phone:'5125559988'});
  const listed=await call('GET','/sales?period=ALL');
  assert.ok(listed.some(row=>row.id===sale.id&&row.status==='COMPLETED'));
  assert.ok(listed.some(row=>row.id===held.id&&row.status==='CANCELLED'));
  assert.equal((await call('GET','/sales?period=INVALID',undefined,400)).error,'Invalid period');
  await call('DELETE',`/products/${latte.id}`);
  assert.equal((await call('GET','/products')).length,1);
  await call('DELETE',`/categories/${category.id}`);
  assert.equal((await call('GET','/categories')).length,0);
  assert.equal((await call('GET','/products')).length,0);
  assert.equal((await call('GET',`/sales/${sale.id}`)).items.length,2);
  const date=deviceDate();
  const report=await call('GET',`/reports/sales?from=${date}&to=${date}`);
  assert.equal(report.totals.orders,1);
  assert.equal(report.orderSources.find(x=>x.order_source==='PHONE').orders,1);
  assert.equal((await call('GET',`/reports/products?from=${date}&to=${date}`)).length,2);
  if (new Date().getTimezoneOffset() !== 0) {
    const edgeUtc = new Date().getTimezoneOffset() < 0 ? '2026-09-30 23:30:00' : '2026-09-30 00:30:00';
    const localDay = deviceDate(new Date(edgeUtc.replace(' ', 'T') + 'Z'));
    const originalCompletedAt = sale.completed_at;
    db.prepare('UPDATE sales SET completed_at=? WHERE id=?').run(edgeUtc, sale.id);
    assert.ok((await call('GET',`/sales?from=${localDay}&to=${localDay}`)).some(row => row.id === sale.id));
    assert.equal((await call('GET',`/reports/sales?from=${localDay}&to=${localDay}`)).totals.orders, 1);
    assert.equal((await call('GET',`/reports/sales?from=${edgeUtc.slice(0,10)}&to=${edgeUtc.slice(0,10)}`)).totals.orders, 0);
    db.prepare('UPDATE sales SET completed_at=? WHERE id=?').run(originalCompletedAt, sale.id);
  }
  const afterCategory=await call('POST','/categories',{name:'Tea'},201);
  const tea=await call('POST','/products',{name:'Tea',categoryId:afterCategory.id,priceCents:300},201);
  let printedSale=await call('POST','/sales',{orderType:'TAKEAWAY',orderSource:'POS'},201);
  printedSale=await call('PUT',`/sales/${printedSale.id}/items/${tea.id}`,{quantity:1});
  printedSale=await call('POST',`/sales/${printedSale.id}/checkout`,{idempotencyKey:'checkout-test-2',paymentMethod:'OTHER',printReceipt:true});
  assert.equal(printedSale.status,'COMPLETED');
  assert.equal(printedSale.printJobs.length,1);
  const backup=await call('POST','/backups',{},201);
  assert.ok(backup.filename.endsWith('.sqlite'));
});
